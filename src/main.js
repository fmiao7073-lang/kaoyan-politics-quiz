// 组卷：题序乱序 + 选项乱序（多选题答案为索引数组，同步映射）
function buildDeck(pool){
  return shuffle(pool).map(q => {
    const order = shuffle([0,1,2,3]);
    return {
      ...q,
      opts: order.map(i => q.o[i]),
      ans: Array.isArray(q.a)
        ? q.a.map(i => order.indexOf(i)).sort((a,b) => a-b)
        : order.indexOf(q.a),
    };
  });
}

